import { useEffect, useRef, type ReactNode } from 'react';
import { identity, isPlaceholder } from '../identity';
import { Logo } from './Logo';
import { SHORTCUTS } from './shortcuts';
import { useStore } from './store';

function Dialog({ title, children }: { title: string; children: ReactNode }) {
  const setDialog = useStore((s) => s.setDialog);
  const ref = useRef<HTMLDialogElement>(null);
  useEffect(() => {
    const d = ref.current;
    if (d && !d.open) d.showModal();
  }, []);
  return (
    <dialog ref={ref} className="dialog" aria-label={title} onClose={() => setDialog('none')} onClick={(e) => e.target === ref.current && setDialog('none')}>
      <header className="dialog-head">
        <h2>{title}</h2>
        <button className="icon-btn" onClick={() => setDialog('none')} aria-label="Close">
          ×
        </button>
      </header>
      <div className="dialog-body">{children}</div>
    </dialog>
  );
}

const shown = (v: string) => !isPlaceholder(v);

export function Dialogs() {
  const dialog = useStore((s) => s.dialog);
  const leanVersion = useStore((s) => s.trace?.meta.leanVersion);
  if (dialog === 'none') return null;

  return (
    <Dialog title="Help">
      <section className="help-section" aria-label="Keyboard shortcuts">
        <h3>Keyboard shortcuts</h3>
        <dl className="shortcuts">
          {SHORTCUTS.map(([keys, what]) => (
            <div key={keys}>
              <dt>
                {keys.split(/\s{2,}| \/ /).map((k) => (
                  <kbd key={k}>{k}</kbd>
                ))}
              </dt>
              <dd>{what}</dd>
            </div>
          ))}
        </dl>
        <p className="muted small">Click any proof line in the editor to jump to it. In a file you're editing, Ctrl+Enter runs it.</p>
        <p className="muted small">Drag the dividers between panels (left and right, top and bottom) to resize them; double-click one to reset it. Your layout is remembered.</p>
      </section>

      <section className="help-section" aria-label="About">
        <h3>About</h3>
        <div className="about">
          <Logo size={34} />
          <div>
            <p>
              {identity.projectName} steps through a Lean 4 proof one line at a time. The goal tree, the hypotheses and the
              visualizations update with every line.
            </p>
            {shown(identity.oneLineStory) && <p className="muted">{identity.oneLineStory}</p>}
            <p className="muted small">
              Proof states are generated by Lean{leanVersion ? ` ${leanVersion}` : ''} with an InfoTree extractor written in Lean.
              Your own files run on a Lean server with core Lean only (no Mathlib).
            </p>
          </div>
        </div>
      </section>

      <section className="help-section" aria-label="Contact">
        <h3>Contact</h3>
        <ul className="contact">
          {shown(identity.yourName) && (
            <li>
              <span className="contact-label">Developer</span>
              {[identity.yourName, identity.teamName, identity.collegeOrOrg].filter(shown).join(' · ')}
            </li>
          )}
          {/* Shown only when it's a real address, so a half-filled value never becomes a broken link. */}
          {shown(identity.contactEmail) && identity.contactEmail.includes('@') && (
            <li>
              <span className="contact-label">Email</span>
              <a href={`mailto:${identity.contactEmail}`}>{identity.contactEmail}</a>
            </li>
          )}
          {shown(identity.githubProfile) && (
            <li>
              <span className="contact-label">GitHub</span>
              <a href={identity.githubProfile} target="_blank" rel="noreferrer">
                {identity.githubProfile.replace(/^https:\/\//, '')}
              </a>
            </li>
          )}
          {shown(identity.repoUrl) && (
            <li>
              <span className="contact-label">Source</span>
              <a href={identity.repoUrl} target="_blank" rel="noreferrer">
                {identity.repoUrl.replace(/^https:\/\/github.com\//, '').replace(/\/$/, '')}
              </a>
            </li>
          )}
          <li>
            <span className="contact-label">Event</span>
            {identity.event}
          </li>
        </ul>
      </section>
    </Dialog>
  );
}
