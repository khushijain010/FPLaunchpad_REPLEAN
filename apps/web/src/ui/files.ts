// "My files": the user's .lean files, kept in this browser's localStorage.
// Files never leave the browser except when the user presses Run (then the source goes to the
// Lean server, as in live mode).

import { create } from 'zustand';
import { normalizeName, uniqueName, type UserFile } from '../core/files';
import { validateTrace } from '../core/validate';
import type { Trace } from '../core/types';

const KEY = 'replean.files.v1';
const OLD_DRAFT_KEY = 'replean.liveDraft';

export const STARTER = `-- A Lean 4 proof. Core Lean only (no imports). Press Run to see it.
theorem imp_chain (p q r : Prop) (hpq : p → q) (hqr : q → r) : p → r := by
  intro hp
  apply hqr
  apply hpq
  exact hp
`;

type FilesState = Readonly<{
  files: readonly UserFile[];
  /** The file open in the editor or player, if any. */
  activeId: string | undefined;
  /** Storage failed (private mode, quota): files work for this visit but won't be kept. */
  storageProblem: boolean;
}>;

const newId = () => `f${Date.now().toString(36)}${Math.random().toString(36).slice(2, 8)}`;

function load(): readonly UserFile[] {
  try {
    const raw = localStorage.getItem(KEY);
    if (raw) {
      const parsed = JSON.parse(raw) as UserFile[];
      // A stored trace that no longer validates is dropped, not trusted.
      return parsed
        .filter((f) => typeof f?.id === 'string' && typeof f.name === 'string' && typeof f.source === 'string')
        .map((f) => {
          if (!f.trace) return f;
          try {
            return { ...f, trace: validateTrace(f.trace) };
          } catch {
            const { trace: _t, tracedSource: _s, ...rest } = f;
            return rest;
          }
        });
    }
    // Carry over the single draft from the earlier live editor, if it was ever changed.
    const draft = localStorage.getItem(OLD_DRAFT_KEY);
    if (draft && draft.trim()) return [{ id: newId(), name: 'proof.lean', source: draft, updatedAt: Date.now() }];
  } catch {
    // Unreadable storage: start empty.
  }
  return [];
}

export const useFiles = create<FilesState>()(() => ({ files: load(), activeId: undefined, storageProblem: false }));

// Persist on every change. If the browser refuses (quota), retry without cached traces, which can
// be regenerated by pressing Run.
useFiles.subscribe((s, prev) => {
  if (s.files === prev.files) return;
  try {
    localStorage.setItem(KEY, JSON.stringify(s.files));
    if (s.storageProblem) useFiles.setState({ storageProblem: false });
  } catch {
    try {
      const slim = s.files.map(({ trace: _t, tracedSource: _s, ...rest }) => rest);
      localStorage.setItem(KEY, JSON.stringify(slim));
    } catch {
      if (!s.storageProblem) useFiles.setState({ storageProblem: true });
    }
  }
});

const update = (id: string, f: (file: UserFile) => UserFile) =>
  useFiles.setState((s) => ({ files: s.files.map((x) => (x.id === id ? f(x) : x)) }));

export const getFile = (id: string | undefined): UserFile | undefined =>
  id === undefined ? undefined : useFiles.getState().files.find((f) => f.id === id);

export function createFile(name = 'proof.lean', source = STARTER): string {
  const id = newId();
  useFiles.setState((s) => ({
    files: [...s.files, { id, name: uniqueName(s.files.map((f) => f.name), name), source, updatedAt: Date.now() }],
  }));
  return id;
}

/** Rename; returns the name actually used (made unique, made safe). */
export function renameFile(id: string, wanted: string): string {
  const others = useFiles.getState().files.filter((f) => f.id !== id).map((f) => f.name);
  const name = uniqueName(others, normalizeName(wanted));
  update(id, (f) => ({ ...f, name, updatedAt: Date.now() }));
  return name;
}

export function deleteFile(id: string): void {
  useFiles.setState((s) => ({ files: s.files.filter((f) => f.id !== id), activeId: s.activeId === id ? undefined : s.activeId }));
}

export const updateSource = (id: string, source: string) => update(id, (f) => ({ ...f, source, updatedAt: Date.now() }));

export const saveTrace = (id: string, trace: Trace, tracedSource: string) =>
  update(id, (f) => ({ ...f, trace, tracedSource }));

export const setActiveFile = (activeId: string | undefined) => useFiles.setState({ activeId });
